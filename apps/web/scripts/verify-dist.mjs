// Fail the build when the static app could break free-tier hosting limits,
// precache something that does not exist, or gain a network/upload path.
import { readdir, readFile, stat } from 'node:fs/promises';
import path from 'node:path';
import { gzipSync } from 'node:zlib';
import { pathToFileURL } from 'node:url';

/** Cloudflare Workers Static Assets free-plan limits (checked 2026-10-18). */
export const limits = {
  files: 20_000,
  fileBytes: 25 * 1024 * 1024,
  // Product budget for gzip-compressed JavaScript, not a host limit.
  javascriptGzipBytes: 300 * 1024,
};

/** Network or upload APIs that application code must never contain. */
export const forbidden =
  /\b(?:fetch\s*\(|XMLHttpRequest|sendBeacon|WebSocket|EventSource|importScripts|RTCPeerConnection)\b|\bfrom\s*["']node:|require\(\s*["'](?:node:|electron)/;

async function list(directory, prefix = '') {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map((entry) =>
      entry.isDirectory()
        ? list(path.join(directory, entry.name), `${prefix}${entry.name}/`)
        : [`${prefix}${entry.name}`],
    ),
  );

  return nested.flat();
}

/** Return every violation; an empty list means the output may ship. */
export async function verifyDist(directory) {
  const problems = [];
  const files = await list(directory);
  if (files.length > limits.files) {
    problems.push(`${files.length} files exceed ${limits.files}`);
  }

  let javascript = 0;
  for (const file of files) {
    const bytes = await readFile(path.join(directory, file));
    if ((await stat(path.join(directory, file))).size > limits.fileBytes) {
      problems.push(`${file} exceeds the 25 MiB static asset limit`);
    }

    if (file.endsWith('.map')) {
      problems.push(`${file}: source maps are not published`);
    }

    if (file.endsWith('.js') && file !== 'sw.js') {
      javascript += gzipSync(bytes).length;
      const match = forbidden.exec(bytes.toString('utf8'));
      if (match) {
        problems.push(`${file}: forbidden network or Node API ${match[0]}`);
      }
    }
  }

  if (javascript > limits.javascriptGzipBytes) {
    problems.push(
      `JavaScript is ${javascript} gzip bytes; budget ${limits.javascriptGzipBytes}`,
    );
  }

  const worker = await readFile(path.join(directory, 'sw.js'), 'utf8').catch(
    () => '',
  );
  const precache = /const PRECACHE = (\[[^\]]*\]);/.exec(worker)?.[1];
  if (!precache || /__PRECACHE__|__VERSION__/.test(worker)) {
    problems.push('sw.js is missing or was not generated by the build');
  } else {
    const urls = JSON.parse(precache);
    if (!urls.includes('/')) {
      problems.push('sw.js does not precache the app shell at /');
    }

    for (const url of urls) {
      const file = url === '/' ? 'index.html' : url.slice(1);
      if (!files.includes(file)) {
        problems.push(`sw.js precaches missing ${url}`);
      }
    }

    for (const file of files) {
      if (
        /^assets\/.+\.(?:js|css|woff2)$/.test(file) &&
        !urls.includes(`/${file}`)
      ) {
        problems.push(`${file} is not precached for offline use`);
      }
    }
  }

  return { problems, files: files.length, javascript };
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  const result = await verifyDist(path.resolve(import.meta.dirname, '../dist'));
  if (result.problems.length) {
    console.error(result.problems.join('\n'));
    process.exit(1);
  }

  console.log(
    `Verified ${result.files} static files; JavaScript ${result.javascript} gzip bytes`,
  );
}
